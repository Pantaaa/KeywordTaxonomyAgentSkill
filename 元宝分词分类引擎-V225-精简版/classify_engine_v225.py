def _read_keywords_from_excel(inp, col=3):
    """读取 Excel 关键词（默认第3列）"""
    kws = []
    try:
        if HAS_PANDAS:
            df = pd.read_excel(inp, engine='openpyxl')
            col_name = df.columns[col - 1]
            kws = [str(v).strip() for v in df[col_name].dropna() if str(v).strip() and str(v).strip() != '关键词']
        else:
            import openpyxl
            wb = openpyxl.load_workbook(inp, read_only=True)
            for sheet in wb.worksheets:
                for row in sheet.iter_rows(values_only=True):
                    if row and len(row) >= col and row[col - 1]:
                        v = str(row[col - 1]).strip()
                        if v and v != '关键词':
                            kws.append(v)
            wb.close()
    except Exception as e:
        print(f'读取失败: {e}', file=sys.stderr)
    return kws


def _write_results(out, results):
    """写出结果（3列：一级标签|二级标签|关键词）"""
    try:
        if HAS_PANDAS:
            pd.DataFrame(results, columns=['一级标签', '二级标签', '关键词']).to_excel(out, index=False)
        else:
            import openpyxl
            wb = openpyxl.Workbook(write_only=True)
            ws = wb.create_sheet()
            ws.append(['一级标签', '二级标签', '关键词'])
            for r in results:
                ws.append(r)
            wb.save(out)
            wb.close()
    except Exception as e:
        print(f'写出失败: {e}', file=sys.stderr)


