def is_competitor_match(text, product, kws):
    """竞品匹配：边界检查 + 排除模式"""
    text_lower = text.lower()
    excludes = EXCLUDE_PATTERNS.get(product, [])
    for exc in excludes:
        if not exc:
            continue
        if exc.lower() in text_lower:
            return False
    for k in kws:
        kl = k.lower()
        idx = text_lower.find(kl)
        if idx >= 0:
            # 中文关键词（如 即梦/可灵）允许后接 ascii 字母（即梦ai/可灵ai 仍是竞品）
            has_cjk = any('\u4e00' <= ch <= '\u9fff' for ch in kl)
            # 前向 ASCII 字母数字边界检查（仅纯英文/数字关键词）
            if idx > 0:
                prev_char = text_lower[idx - 1]
                if prev_char.isascii() and prev_char.isalnum() and not has_cjk:
                    continue
            next_idx = idx + len(kl)
            if next_idx < len(text_lower):
                next_char = text_lower[next_idx]
                if next_char.isascii() and next_char.isalnum() and not has_cjk:
                    continue
            return True
    return False


